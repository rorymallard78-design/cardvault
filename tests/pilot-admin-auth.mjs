import assert from 'node:assert/strict';
import worker from '../pilot-backend/src/index.js';
const url='https://cardvault-pilot.example';
const env={DB:{prepare(){return {first:async()=>({max_scans:1000,max_spend_micro_usd:20000000,claimed_scans:0,completed_scans:0,failed_scans:0,spent_micro_usd:0,reserved_micro_usd:0}),all:async()=>({results:[]})}}},ANTHROPIC_API_KEY:'testkey',ADMIN_TOKEN:'secret-value',ALLOWED_ORIGIN:'https://rorymallard78-design.github.io'};
const health=await worker.fetch(new Request(url+'/v1/health'),env);assert.equal(health.status,200);
const h=await health.json();assert.equal(h.adminSecretPresent,true);assert.equal(h.release,'pilot-admin-auth-check-1');
const ok=await worker.fetch(new Request(url+'/v1/admin/stats',{headers:{Origin:url,Authorization:'Bearer secret-value'}}),env);
assert.equal(ok.status,200);
const wrong=await worker.fetch(new Request(url+'/v1/admin/stats',{headers:{Origin:url,Authorization:'Bearer bad'}}),env);
assert.equal(wrong.status,401);
assert.match((await wrong.json()).error,/does not match/);
const noAdmin=await worker.fetch(new Request(url+'/v1/admin/stats',{headers:{Origin:url}}),{...env,ADMIN_TOKEN:undefined});
assert.equal(noAdmin.status,503);
assert.match((await noAdmin.json()).error,/missing/);
const foreign=await worker.fetch(new Request(url+'/v1/admin/stats',{headers:{Origin:'https://other.invalid',Authorization:'Bearer secret-value'}}),env);
assert.equal(foreign.status,403);
const pwa=await worker.fetch(new Request(url+'/v1/admin/stats',{headers:{Origin:env.ALLOWED_ORIGIN,Authorization:'Bearer secret-value'}}),env);
assert.equal(pwa.status,200);
console.log('Admin origin, token and missing-secret diagnostics passed.');
